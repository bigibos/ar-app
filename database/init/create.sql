-- -----------------------------------------------------
-- Schema ar_app
-- -----------------------------------------------------

DROP SCHEMA IF EXISTS ar_app CASCADE;
CREATE SCHEMA ar_app;

-- Use this schema for the following statements.
SET search_path TO ar_app;

-- -----------------------------------------------------
-- Table ar_markers
-- -----------------------------------------------------

CREATE TABLE ar_markers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 52) PRIMARY KEY,
    barcode_value INTEGER NOT NULL,
    barcode_link VARCHAR(1024) NOT NULL
);

-- -----------------------------------------------------
-- Table galleries
-- -----------------------------------------------------

CREATE TABLE galleries (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 63) PRIMARY KEY,
    name VARCHAR(256) NOT NULL,
    description VARCHAR(1024)
);

-- -----------------------------------------------------
-- Table paintings
-- -----------------------------------------------------

CREATE TABLE paintings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 30),
    gallery_id INTEGER NOT NULL,
    marker_id INTEGER NOT NULL,
    name VARCHAR(256) NOT NULL,
    author VARCHAR(256) NOT NULL,
    image_link VARCHAR(1024) NOT NULL,
    PRIMARY KEY (gallery_id, marker_id),
    CONSTRAINT paintings_id_key UNIQUE (id),
    CONSTRAINT fk_paintings_ar_markers
        FOREIGN KEY (marker_id) REFERENCES ar_markers (id),
    CONSTRAINT fk_paintings_galleries
        FOREIGN KEY (gallery_id) REFERENCES galleries (id)
);

CREATE INDEX fk_paintings_galleries_idx ON paintings (gallery_id);
CREATE INDEX fk_paintings_ar_markers_idx ON paintings (marker_id);

-- -----------------------------------------------------
-- Table users
-- -----------------------------------------------------

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 56) PRIMARY KEY,
    username VARCHAR(128) NOT NULL,
    email VARCHAR(516),
    hash VARCHAR(1024) NOT NULL,
    auth_token VARCHAR(1024),
    gallery_id INTEGER,
    CONSTRAINT fk_users_galleries
        FOREIGN KEY (gallery_id) REFERENCES galleries (id)
);

CREATE UNIQUE INDEX username_UNIQUE ON users (username);
CREATE INDEX fk_users_galleries_idx ON users (gallery_id);
